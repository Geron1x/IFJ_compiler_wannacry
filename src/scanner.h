#ifndef IFJ_SCANNER_H
#define IFJ_SCANNER_H

#include <ctype.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "error.h"

/**
 * @union Val
 * @brief Stores the attribute value of a specific token.
 */

typedef union
{
    char* identifier;
    char* string;
    double numberFloat;
    long long int numberInt;
} Val;

/**
 * @enum Type
 * @brief Enumeration of all valid token types in the IFJ26 language.
 */

typedef enum
{
    TYPE_DEF,
    TYPE_DO,
    TYPE_DOUBLE,
    TYPE_ELSE,
    TYPE_IF,
    TYPE_IMPORT,
    TYPE_INT,
    TYPE_RETURN,
    TYPE_STRING,
    TYPE_THEN,
    TYPE_UNIT,
    TYPE_VAL,
    TYPE_VAR,
    TYPE_WHILE,
    TYPE_ADD,
    TYPE_SUB,
    TYPE_MUL,
    TYPE_DIV,
    TYPE_LESSER,
    TYPE_LESSER_EQUAL,
    TYPE_EQUAL,
    TYPE_BIGGER_EQUAL,
    TYPE_BIGGER,
    TYPE_NOT_EQUAL,
    TYPE_ASSIGNMENT,
    TYPE_LEFT_PAREN,
    TYPE_RIGHT_PAREN,
    TYPE_DOUBLE_DOT,
    TYPE_COMMA,
    TYPE_SEMICOLON,
    TYPE_DOT,
    TYPE_MAIN,
    TYPE_EOL,
    TYPE_EOF,
    TYPE_INDENT,
    TYPE_DEDENT,
    TYPE_ERROR,
    TYPE_IDENTIFIER,
    TYPE_STRING_LITERAL,
    TYPE_INT_LITERAL,
    TYPE_DOUBLE_LITERAL,
    TYPE_UNIT_LITERAL,
    TYPE_EXCLAMATION
} Type;

/**
 * @struct Token
 * @brief Represents a single lexical token generated by the scanner.
 */
typedef struct
{
    Val value;
    Type type;
    int line;
} Token;

/**
 * @struct Scanner
 * @brief Holds the internal state of the lexical analyzer.
 */

typedef struct
{
    int line;
    int firstRead;
    FILE* stream;

    int indentStack[128];
    int indentTop;
    int pendingDedents;
    int atLineStart;
    int parenLevel;
} Scanner;

/**
 * @brief Initializes the scanner state and binds it to an input stream.
 *
 * Sets up the initial line number, indentation stack, and formatting flags
 * required for correct tokenization of the IFJ26 language.
 *
 * @param scanner Pointer to the Scanner structure to be initialized.
 * @param stream The input file stream to read characters from.
 */

void scannerInit(Scanner* scanner, FILE* stream);

/**
 * @brief Reads the next token from the input stream.
 *
 * @param token Pointer to the Token structure where the scanned token will be
 * stored.
 * @param scanner Pointer to the Scanner structure representing the current
 * scanner state.
 * @return int 0 on success, or a non-zero error code (e.g., lexical error 1) on
 * failure.
 */

int getToken(Token* token, Scanner* scanner);

#endif  // IFJ_SCANNER_H